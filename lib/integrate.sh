# shellcheck shell=bash
# Hyprland and Omarchy-menu integration, installed as marked, idempotent,
# reversible blocks. Everything we add lives between
#   >>> io.github.saurasanchezpablo.tabby ... >>>  and  <<< io.github.saurasanchezpablo.tabby <<<
# and a timestamped backup of the edited file is kept in $OT_STATE_DIR/backups.

OT_HYPR_DIR="${OMARCHY_TABBY_HYPR_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/hypr}"
OT_HYPR_MAIN="$OT_HYPR_DIR/hyprland.lua"
OT_HYPR_FILE="$OT_HYPR_DIR/omarchy-tabby.lua"
OT_MENU_FILE="${OMARCHY_TABBY_MENU_FILE:-${XDG_CONFIG_HOME:-$HOME/.config}/omarchy/extensions/omarchy-menu.jsonc}"
OT_DEFAULT_FOCUS_KEY="SUPER + ALT + T"
OT_DEFAULT_DROPDOWN_KEY="SUPER + grave"

block_begin() { printf '%s >>> %s (managed by omarchy-tabby) >>>' "$1" "$PLUGIN_ID"; }
block_end() { printf '%s <<< %s <<<' "$1" "$PLUGIN_ID"; }

backup_file() {
  local file="$1" dest
  [[ -f $file ]] || return 0
  dest="$OT_STATE_DIR/backups"
  ensure_private_dir "$OT_STATE_DIR" && ensure_private_dir "$dest" || return 1
  cp -p -- "$file" "$dest/$(basename "$file").$(date +%Y%m%d-%H%M%S).bak"
}

# has_block FILE COMMENT_PREFIX
has_block() {
  [[ -f $1 ]] && grep -qF -- "$(block_begin "$2")" "$1"
}

# Exactly one begin marker followed by one end marker.
block_complete() {
  local file="$1" prefix="$2"
  awk -v b="$(block_begin "$prefix")" -v e="$(block_end "$prefix")" '
    index($0, b) == 1 { nb++; if (ne) bad = 1 }
    index($0, e) == 1 { ne++; if (!nb) bad = 1 }
    END { exit !(nb == 1 && ne == 1 && !bad) }
  ' "$file"
}

# Print FILE without our block (only call when block_complete).
without_block() {
  local file="$1" prefix="$2"
  awk -v b="$(block_begin "$prefix")" -v e="$(block_end "$prefix")" '
    index($0, b) == 1 { skip = 1; next }
    skip && index($0, e) == 1 { skip = 0; next }
    !skip { print }
  ' "$file"
}

remove_block() {
  local file="$1" prefix="$2"
  has_block "$file" "$prefix" || return 0
  if ! block_complete "$file" "$prefix"; then
    warn "the omarchy-tabby block in $file has lost a marker; remove it by hand"
    return 1
  fi
  backup_file "$file" || return 1
  without_block "$file" "$prefix" | replace_file "$file"
}

# Key combos currently bound in Hyprland, as "MODMASK KEY" lines (uppercase).
bound_keys() {
  have_hyprctl || return 0
  hyprctl binds -j 2>/dev/null | jq -r '.[] | select((.key // "") != "") | "\(.modmask) \(.key | ascii_upcase)"' 2>/dev/null
}

# "SUPER + ALT + T" -> "72 T"
combo_to_bind() {
  local combo="${1// /}" mask=0 part key=""
  local IFS=+
  for part in $combo; do
    case "${part^^}" in
    SUPER | WIN | LOGO | MOD4) ((mask |= 64)) ;;
    SHIFT) ((mask |= 1)) ;;
    CTRL | CONTROL) ((mask |= 4)) ;;
    ALT | MOD1) ((mask |= 8)) ;;
    *) key="${part^^}" ;;
    esac
  done
  printf '%s %s\n' "$mask" "$key"
}

key_is_free() {
  local wanted
  wanted="$(combo_to_bind "$1")"
  ! bound_keys | grep -qxF -- "$wanted"
}

valid_combo() {
  [[ $1 =~ ^[A-Za-z0-9_+\ ]+$ ]]
}

# hypr_lua FOCUS_KEY DROPDOWN_KEY  (empty key = no binding)
hypr_lua() {
  local focus_key="$1" dropdown_key="$2" bin
  # o.bind runs the command through a shell: quote the path.
  bin="$(printf '%q' "$OT_BIN_LINK")"
  cat <<EOF
-- Generated by omarchy-tabby $OT_VERSION. Do not edit: rerun
-- \`omarchy-tabby integrate install\` (or remove with \`omarchy-tabby integrate remove\`).

-- Tabby is a terminal: this enables Omarchy's universal copy/paste
-- (SUPER+C/V send CTRL/SHIFT+Insert to terminals) and every terminal rule.
o.window("^(tabby)$", { tag = "+terminal" })
EOF
  if [[ -n $focus_key ]]; then
    printf 'o.bind(%s, "Tabby", %s)\n' "$(jq -n --arg k "$focus_key" '$k')" "$(jq -n --arg c "$bin focus" '$c')"
  fi
  if [[ -n $dropdown_key ]]; then
    printf 'o.bind(%s, "Tabby dropdown", %s)\n' "$(jq -n --arg k "$dropdown_key" '$k')" "$(jq -n --arg c "$bin scratchpad" '$c')"
  fi
}

hypr_install() {
  local focus_key="$1" dropdown_key="$2"
  [[ -f $OT_HYPR_MAIN ]] || {
    warn "no $OT_HYPR_MAIN; skipping Hyprland integration"
    return 0
  }
  for k in "$focus_key" "$dropdown_key"; do
    [[ -z $k ]] || valid_combo "$k" || die "invalid key combination: $k"
  done
  # Our own previous bindings are about to be replaced, so they don't count as conflicts.
  if [[ -f $OT_HYPR_FILE ]] && grep -qF "$OT_BIN_LINK focus" "$OT_HYPR_FILE"; then
    :
  elif [[ -n $focus_key ]] && ! key_is_free "$focus_key"; then
    warn "$focus_key is already bound; not binding Tabby to it"
    focus_key=""
  fi
  if [[ -f $OT_HYPR_FILE ]] && grep -qF "$OT_BIN_LINK scratchpad" "$OT_HYPR_FILE"; then
    :
  elif [[ -n $dropdown_key ]] && ! key_is_free "$dropdown_key"; then
    warn "$dropdown_key is already bound; not binding the Tabby dropdown to it"
    dropdown_key=""
  fi

  hypr_lua "$focus_key" "$dropdown_key" | write_atomic "$OT_HYPR_FILE" 644 || die "cannot write $OT_HYPR_FILE"

  if has_block "$OT_HYPR_MAIN" -- && ! block_complete "$OT_HYPR_MAIN" --; then
    die "the omarchy-tabby block in $OT_HYPR_MAIN has lost a marker; fix it by hand"
  fi
  if ! has_block "$OT_HYPR_MAIN" --; then
    local tmp
    tmp="$(mktemp)" || die "cannot create a temporary file"
    {
      cat -- "$OT_HYPR_MAIN"
      # Only add a newline if the file lacks one, so removal restores it exactly.
      [[ -z $(tail -c1 -- "$OT_HYPR_MAIN") ]] || echo
      printf '%s\n' "$(block_begin --)"
      # pcall: a broken generated file must never break the Hyprland config.
      # shellcheck disable=SC2016
      printf '%s\n' 'do local ok, err = pcall(dofile, (os.getenv("XDG_CONFIG_HOME") or ((os.getenv("HOME") or "") .. "/.config")) .. "/hypr/omarchy-tabby.lua"); if not ok then print("omarchy-tabby: " .. tostring(err)) end end'
      printf '%s\n' "$(block_end --)"
    } >"$tmp"
    # Appending after a top-level `return` would be a syntax error that stops
    # Hyprland from loading its config: check before writing.
    if ! lua_syntax_ok "$tmp"; then
      rm -f -- "$tmp"
      die "adding the loader would break $OT_HYPR_MAIN (does it end with 'return'?); add it by hand, see README"
    fi
    backup_file "$OT_HYPR_MAIN" || die "cannot back up $OT_HYPR_MAIN"
    replace_file "$OT_HYPR_MAIN" <"$tmp" || die "cannot update $OT_HYPR_MAIN"
    rm -f -- "$tmp"
  fi
  hypr_reload
}

lua_syntax_ok() {
  local luac
  for luac in luac5.4 luac; do
    if command -v "$luac" >/dev/null 2>&1; then
      "$luac" -p -- "$1" >/dev/null 2>&1
      return
    fi
  done
  return 0 # no checker available
}

hypr_remove() {
  remove_block "$OT_HYPR_MAIN" -- || warn "left $OT_HYPR_MAIN unchanged"
  rm -f -- "$OT_HYPR_FILE"
  hypr_reload
}

# Reload Hyprland and report config errors (they would otherwise only show as
# an on-screen banner).
hypr_reload() {
  have_hyprctl || return 0
  [[ -n ${OMARCHY_TABBY_NO_RELOAD:-} ]] && return 0
  hyprctl reload >/dev/null 2>&1 || true
  sleep 0.3
  local errors
  errors="$(hyprctl configerrors 2>/dev/null | grep -i tabby || true)"
  [[ -z $errors ]] || warn "Hyprland reported: $errors"
}

# One `  "id": {...},` line per entry. Glyphs are written as \uXXXX escapes so
# no tool along the way can drop the private-use codepoints.
ascii_escape() {
  if command -v perl >/dev/null 2>&1; then
    perl -CSD -pe 's/([^\x00-\x7f])/sprintf("\\u%04x", ord($1))/ge'
  else
    cat
  fi
}

menu_entries() {
  jq -nr --arg bin "$(printf '%q' "$OT_BIN_LINK")" '
    def g($cp): [$cp] | implode;  # Nerd Font glyph by codepoint
    def toggle($key; $icon; $label):
      { icon: $icon, label: $label,
        checked: "[[ $(\($bin) settings get \($key)) == true ]]",
        action: "\($bin) settings toggle \($key)" };
    [
      ["setup.default.terminal.tabby", { icon: g(62601), label: "Tabby", when: "command -v tabby >/dev/null",
                                         checked: "\($bin) default status -q", action: "\($bin) default on" }],
      ["setup.tabby", { icon: g(62601), label: "Tabby", title: "Tabby integration", aliases: ["tabby"],
                        when: "command -v tabby >/dev/null" }],
      ["setup.tabby.colors", toggle("syncColors"; g(61948); "Sync colours with theme")],
      ["setup.tabby.font", toggle("syncFont"; g(61489); "Sync font")],
      ["setup.tabby.clipboard", toggle("clipboardKeys"; g(61674); "Universal clipboard")],
      ["setup.tabby.cwd", toggle("smartCwd"; g(61564); "Follow the Tabby tab directory")],
      ["setup.tabby.default", { icon: g(61728), label: "Default terminal",
                                checked: "\($bin) default status -q", action: "\($bin) default toggle" }],
      ["setup.tabby.apply", { icon: g(61473), label: "Re-apply Omarchy theme and font", action: "\($bin) apply" }]
    ][] | "  \(.[0] | tojson): \(.[1] | tojson),"' | ascii_escape
}

# Python is used only to check the result the way the shell parses it
# (whole-line // comments and trailing commas removed, then strict JSON).
jsonc_valid() {
  python3 -I -c '
import json, re, sys
text = open(sys.argv[1], encoding="utf-8").read()
text = re.sub(r"(?m)^\s*//[^\n]*(\n|$)", "", text)
text = re.sub(r",(\s*[}\]])", r"\1", text)
if text.strip():
    json.loads(text)
' "$1" 2>/dev/null
}

menu_install() {
  local dir tmp
  dir="$(dirname "$OT_MENU_FILE")"
  mkdir -p -- "$dir" || die "cannot create $dir"
  if [[ ! -e $OT_MENU_FILE ]]; then
    printf '{\n}\n' | write_atomic "$OT_MENU_FILE" 644 || die "cannot create $OT_MENU_FILE"
  fi
  if has_block "$OT_MENU_FILE" '  //' && ! block_complete "$OT_MENU_FILE" '  //'; then
    warn "the omarchy-tabby block in $OT_MENU_FILE has lost a marker; fix it by hand"
    return 1
  fi
  tmp="$(mktemp)" || die "cannot create a temporary file"
  # Insert right after the top-level opening brace (the first line that is
  # not blank or a comment): every entry ends with a comma, so whatever
  # follows (user entries or the closing brace) stays valid JSONC.
  {
    if has_block "$OT_MENU_FILE" '  //'; then without_block "$OT_MENU_FILE" '  //'; else cat -- "$OT_MENU_FILE"; fi
  } | OT_B="$(block_begin '  //')" OT_E="$(block_end '  //')" OT_ENTRIES="$(menu_entries)" awk '
    !seen && /^[[:space:]]*(\/\/.*)?$/ { print; next }
    !seen {
      seen = 1
      if ($0 ~ /^[[:space:]]*\{[[:space:]]*$/) { print; print ENVIRON["OT_B"]; print ENVIRON["OT_ENTRIES"]; print ENVIRON["OT_E"]; next }
      bad = 1
    }
    { print }
    END { if (!seen || bad) exit 3 }
  ' >"$tmp"
  local rc=$?
  if ((rc != 0)); then
    rm -f -- "$tmp"
    warn "$OT_MENU_FILE does not start with '{' on its own line; add the Tabby entries by hand (see README)"
    return 1
  fi
  if command -v python3 >/dev/null 2>&1 && ! jsonc_valid "$tmp"; then
    rm -f -- "$tmp"
    warn "refusing to write an invalid $OT_MENU_FILE"
    return 1
  fi
  backup_file "$OT_MENU_FILE" || die "cannot back up $OT_MENU_FILE"
  replace_file "$OT_MENU_FILE" <"$tmp"
  local written=$?
  rm -f -- "$tmp"
  return $written
}

menu_remove() {
  [[ -f $OT_MENU_FILE ]] || return 0
  remove_block "$OT_MENU_FILE" '  //'
}

cmd_integrate() {
  local sub="${1:-status}" focus_key="$OT_DEFAULT_FOCUS_KEY" dropdown_key="$OT_DEFAULT_DROPDOWN_KEY"
  shift || true
  while (($#)); do
    case "$1" in
    --focus-key=*) focus_key="${1#*=}" ;;
    --dropdown-key=*) dropdown_key="${1#*=}" ;;
    --no-keys) focus_key="" dropdown_key="" ;;
    *) die "unknown option $1" ;;
    esac
    shift
  done
  case "$sub" in
  install)
    hypr_install "$focus_key" "$dropdown_key"
    menu_install || true
    ;;
  remove)
    hypr_remove
    menu_remove
    ;;
  status)
    printf 'hyprland\t%s\n' "$(has_block "$OT_HYPR_MAIN" -- && [[ -f $OT_HYPR_FILE ]] && echo installed || echo absent)"
    printf 'menu\t%s\n' "$(has_block "$OT_MENU_FILE" '  //' && echo installed || echo absent)"
    ;;
  *) die "usage: omarchy-tabby integrate [install [--focus-key=COMBO] [--dropdown-key=COMBO] [--no-keys] | remove | status]" ;;
  esac
}
